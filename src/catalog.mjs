const img = (src, w, h, alt) => ({ src: `img/${src}.webp`, w, h, alt });
// Ролик из site/video: name.mp4 и постеры name-0.webp / name-1.webp (первый и последний кадр). У горизонтальных есть вариант для телефона:
// вертикальный срез вокруг сюжета name-m.mp4 с постерами name-m0.webp / name-m1.webp; focus — где сюжет по ширине кадра, в процентах.
// Пережатие и срезы — research/video/s2/encode.py.
